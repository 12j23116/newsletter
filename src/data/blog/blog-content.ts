const topicImageCounters: Record<string, number> = {};

function assignImage(post: BlogPost): BlogPost {
  const images = topicImages[post.topic];
  if (!images) return post;
  const idx = topicImageCounters[post.topic] = (topicImageCounters[post.topic] || 0) % images.length;
  topicImageCounters[post.topic]++;
  return { ...post, image: `/images/${images[idx]}` };
}

